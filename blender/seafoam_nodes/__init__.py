"""Seafoam Nodes: stylized breaking waves and foam for Blender.

Adds a "Seafoam" submenu to Add in the Geometry Node and Shader editors, and
"Seafoam Beach" / "Seafoam Ocean" to Add in the 3D Viewport. Node groups are
generated by Python the first time you add them, so there is no asset file.
"""

bl_info = {
    "name": "Seafoam Nodes",
    "author": "Seafoam project",
    "version": (0, 1, 0),
    "blender": (4, 2, 0),
    "location": "Geometry/Shader Editor > Add > Seafoam, 3D Viewport > Add > Seafoam",
    "description": "Stylized shoaling, curling and breaking waves, foam, swash and spray",
    "category": "Node",
}

import bpy

from . import geometry_groups, shader_groups

GEOMETRY_GROUPS = list(geometry_groups.BUILDERS)
SHADER_GROUPS = list(shader_groups.BUILDERS)
DEPENDENCIES = {"SF Water Shader": ["SF Foam Look"]}


def ensure_group(name, rebuild=False):
    """Return the node group, building it (and what it uses) if needed."""
    for dependency in DEPENDENCIES.get(name, []):
        ensure_group(dependency, rebuild)
    group = bpy.data.node_groups.get(name)
    if group is None or rebuild:
        builder = geometry_groups.BUILDERS.get(name) or shader_groups.BUILDERS[name]
        group = builder()
    return group


def build_all(rebuild=True):
    return [ensure_group(name, rebuild) for name in GEOMETRY_GROUPS + SHADER_GROUPS]


class SEAFOAM_OT_add_group(bpy.types.Operator):
    """Add a Seafoam node group at the mouse"""

    bl_idname = "node.seafoam_add_group"
    bl_label = "Add Seafoam Node"
    bl_options = {"REGISTER", "UNDO"}

    group: bpy.props.StringProperty()

    @classmethod
    def poll(cls, context):
        return context.space_data is not None and context.space_data.type == "NODE_EDITOR" and context.space_data.edit_tree

    def invoke(self, context, event):
        tree = context.space_data.edit_tree
        group = ensure_group(self.group)
        node_type = "GeometryNodeGroup" if tree.bl_idname == "GeometryNodeTree" else "ShaderNodeGroup"
        for node in tree.nodes:
            node.select = False
        node = tree.nodes.new(node_type)
        node.node_tree = group
        node.location = context.space_data.cursor_location
        node.select = True
        tree.nodes.active = node
        bpy.ops.node.translate_attach_remove_on_cancel("INVOKE_DEFAULT")
        return {"FINISHED"}


class SEAFOAM_OT_rebuild(bpy.types.Operator):
    """Regenerate every Seafoam node group (resets edits made inside them)"""

    bl_idname = "node.seafoam_rebuild"
    bl_label = "Rebuild Seafoam Groups"
    bl_options = {"REGISTER", "UNDO"}

    def execute(self, context):
        build_all(rebuild=True)
        return {"FINISHED"}


class SEAFOAM_OT_add_scene(bpy.types.Operator):
    """Build a ready-to-render Seafoam setup in the current scene"""

    bl_idname = "object.seafoam_add_scene"
    bl_label = "Add Seafoam Scene"
    bl_options = {"REGISTER", "UNDO"}

    kind: bpy.props.EnumProperty(items=[
        ("BEACH", "Beach", "Shoaling, curling and breaking waves on sand"),
        ("OCEAN", "Ocean", "Open sea with Gerstner waves and whitecaps"),
    ])
    spacing: bpy.props.FloatProperty(
        name="Grid Spacing", default=0.3, min=0.1, max=2.0, unit="LENGTH",
        description="Water mesh spacing. 0.3 m shows the curl; use 0.6 m or more on slower machines")

    def execute(self, context):
        from . import scenes

        if self.kind == "BEACH":
            scenes.build_beach_scene(spacing=self.spacing)
        else:
            scenes.build_ocean_scene(spacing=self.spacing)
        return {"FINISHED"}


class SEAFOAM_OT_sync_sun(bpy.types.Operator):
    """Point the Seafoam toon materials at the scene's sun lamp (run after moving the sun)"""

    bl_idname = "object.seafoam_sync_sun"
    bl_label = "Sync Seafoam Sun"
    bl_options = {"REGISTER", "UNDO"}

    def execute(self, context):
        sun = next((o for o in context.scene.objects if o.type == "LIGHT" and o.data.type == "SUN"), None)
        if sun is None:
            self.report({"WARNING"}, "No sun lamp in the scene")
            return {"CANCELLED"}
        shader_groups.set_sun_direction(sun.matrix_world.col[2].xyz.normalized())
        return {"FINISHED"}


class NODE_MT_seafoam(bpy.types.Menu):
    bl_idname = "NODE_MT_seafoam"
    bl_label = "Seafoam"

    def draw(self, context):
        tree = context.space_data.edit_tree
        names = GEOMETRY_GROUPS if tree and tree.bl_idname == "GeometryNodeTree" else SHADER_GROUPS
        for name in names:
            self.layout.operator(SEAFOAM_OT_add_group.bl_idname, text=name).group = name
        self.layout.separator()
        self.layout.operator(SEAFOAM_OT_rebuild.bl_idname)


class VIEW3D_MT_seafoam(bpy.types.Menu):
    bl_idname = "VIEW3D_MT_seafoam"
    bl_label = "Seafoam"

    def draw(self, context):
        self.layout.operator(SEAFOAM_OT_add_scene.bl_idname, text="Seafoam Beach").kind = "BEACH"
        self.layout.operator(SEAFOAM_OT_add_scene.bl_idname, text="Seafoam Ocean").kind = "OCEAN"
        self.layout.separator()
        self.layout.operator(SEAFOAM_OT_sync_sun.bl_idname)


def node_menu(self, context):
    tree = context.space_data.edit_tree
    if tree and tree.bl_idname in {"GeometryNodeTree", "ShaderNodeTree"}:
        self.layout.menu(NODE_MT_seafoam.bl_idname)


def view3d_menu(self, context):
    self.layout.menu(VIEW3D_MT_seafoam.bl_idname)


CLASSES = (SEAFOAM_OT_add_group, SEAFOAM_OT_rebuild, SEAFOAM_OT_add_scene, SEAFOAM_OT_sync_sun,
           NODE_MT_seafoam, VIEW3D_MT_seafoam)


def register():
    for cls in CLASSES:
        bpy.utils.register_class(cls)
    bpy.types.NODE_MT_add.append(node_menu)
    bpy.types.VIEW3D_MT_add.append(view3d_menu)


def unregister():
    bpy.types.VIEW3D_MT_add.remove(view3d_menu)
    bpy.types.NODE_MT_add.remove(node_menu)
    for cls in reversed(CLASSES):
        bpy.utils.unregister_class(cls)
