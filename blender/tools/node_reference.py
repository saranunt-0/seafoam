"""Write blender/NODE_REFERENCE.md from the node groups themselves.

    python blender/tools/node_reference.py        (bpy module, Python 3.11)
    blender --background --factory-startup --python blender/tools/node_reference.py
"""

import math
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import bpy  # noqa: E402

import seafoam_nodes  # noqa: E402

KIND = {
    "NodeSocketGeometry": "Geometry", "NodeSocketFloat": "Float", "NodeSocketInt": "Integer",
    "NodeSocketVector": "Vector", "NodeSocketColor": "Color", "NodeSocketString": "String",
    "NodeSocketMaterial": "Material", "NodeSocketShader": "Shader", "NodeSocketBool": "Boolean",
}


def value(item):
    if not hasattr(item, "default_value") or item.socket_type in ("NodeSocketMaterial",):
        return ""
    v = item.default_value
    if item.socket_type == "NodeSocketString":
        return f"`{v}`"
    if item.socket_type in ("NodeSocketVector", "NodeSocketColor"):
        return "(" + ", ".join(f"{c:g}" for c in tuple(v)[:3]) + ")"
    if getattr(item, "subtype", "") == "ANGLE":
        return f"{math.degrees(v):g}°"
    return f"{v:g}"


def describe(group):
    lines = [f"## {group.name}", "", group.description, ""]
    sockets = [i for i in group.interface.items_tree if i.item_type == "SOCKET"]
    rows = [i for i in sockets if i.in_out == "INPUT"] + [i for i in sockets if i.in_out == "OUTPUT"]
    lines += ["| Socket | Type | Default | What it does |", "|---|---|---|---|"]
    for item in rows:
        direction = "out: " if item.in_out == "OUTPUT" else ""
        lines.append(f"| {direction}{item.name} | {KIND.get(item.socket_type, item.socket_type)} | {value(item)} | {item.description} |")
    return "\n".join(lines) + "\n"


def main():
    seafoam_nodes.register()
    groups = seafoam_nodes.build_all()
    text = [
        "# Seafoam node reference",
        "",
        "Generated by `blender/tools/node_reference.py` from the node groups, so it matches the code.",
        "Geometry groups are listed first, then shader groups. All geometry groups also work as modifiers.",
        "",
    ]
    text += [describe(g) for g in groups]
    out = ROOT / "NODE_REFERENCE.md"
    out.write_text("\n".join(text))
    print(f"Wrote {out}", flush=True)
    os._exit(0)   # bpy as a module can hang on normal interpreter exit


main()
